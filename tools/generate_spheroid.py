#!/usr/bin/env python3
"""Example build-time SymPy generator; no SymPy dependency in the C++ core.

Usage: python tools/generate_spheroid.py --output generated/spheroid3.hpp
The generated class has the same interface as the hand-written geometries.
Focal coordinates remain runtime parameters; only spatial derivatives are taken.
"""

import argparse
from pathlib import Path

import sympy as sp
from sympy.printing import cxxcode


def generate() -> str:
    x = sp.symbols("x0:3", real=True)
    a = sp.symbols("a0:3", real=True)
    b = sp.symbols("b0:3", real=True)
    phi = sum(sp.sqrt(sum((x[i] - c[i]) ** 2 for i in range(3))) for c in (a, b))
    gradient = [sp.diff(phi, xi) for xi in x]
    hessian = sp.hessian(phi, x)
    entries = [(i, j) for i in range(3) for j in range(i, 3)]
    names = ["out.value"] + [f"out.gradient[{i}]" for i in range(3)]
    names += [f"out.hessian[{i}][{j}]" for i, j in entries]
    temps, exprs = sp.cse([phi, *gradient, *(hessian[i, j] for i, j in entries)])
    lines = ["// Generated by tools/generate_spheroid.py; do not edit.",
             "#pragma once", '#include <genradon/geometry.hpp>',
             "namespace genradon {", "class GeneratedSpheroid3 {", "public:",
             "    GeneratedSpheroid3(Vec<3> a, Vec<3> b) : a_(a), b_(b), reference_(a,b) {}",
             "    double value(const Vec<3>& x) const { return reference_.value(x); }",
             "    double hessian_bound(const Box<3>& box) const { return reference_.hessian_bound(box); }",
             "    Jet<3> jet(const Vec<3>& x) const {",
             "        if (norm(subtract(x,a_)) == 0 || norm(subtract(x,b_)) == 0)",
             '            throw std::domain_error("Undefined derivatives at a focus");',
             "        Jet<3> out;"]
    for prefix, source in (("x", "x"), ("a", "a_"), ("b", "b_")):
        for i in range(3):
            lines.append(f"        const double {prefix}{i} = {source}[{i}];")
    for symbol, expression in temps:
        lines.append(f"        const double {symbol} = {cxxcode(expression)};")
    for name, expression in zip(names, exprs):
        lines.append("        " + cxxcode(expression, assign_to=name))
    for i, j in entries:
        if i != j:
            lines.append(f"        out.hessian[{j}][{i}] = out.hessian[{i}][{j}];")
    lines += ["        return out;", "    }", "private:",
              "    Vec<3> a_, b_;", "    Spheroid<3> reference_;", "};", "} // namespace genradon", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(generate(), encoding="utf-8")
